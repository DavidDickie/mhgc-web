// ---------------------------------------------------------------- battles
const PHASE_LABEL = { space: "Space combat", raid: "Raids and bombardment", ground: "Ground combat", status: "System status", capture: "Capture" };
const STATUS = { 0: "Normal", 1: "Under attack", 2: "Interdicted" };

export function battle(c, v) {
  const sys = c.system !== null && c.system !== undefined ? knownSystems().find(s => s.id === c.system) : null;
  const place = sys ? `${sys.name || "a system"} (${xy(c.x, c.y)})` : `deep space ${xy(c.x, c.y)}`;
  const names = c.participant_names || {};
  const pname = id => names[id] || names[String(id)] || raceName(id);
  const parts = c.participants.map(pname);
  const outcome = [];
  if (c.owner_before !== c.owner_after && c.owner_after !== null && c.owner_after !== undefined) outcome.push(`System captured by the ${pname(c.owner_after)}`);
  if (c.status_before !== c.status_after && c.status_after !== null && c.status_after !== undefined) outcome.push(`Status ${STATUS[c.status_before] || c.status_before} → ${STATUS[c.status_after] || c.status_after}`);
  const sides = c.participants.map(p => {
    const ships = c.ships.filter(s => s.owner === p), troops = c.troops.filter(t => t.owner === p);
    const count = arr => { const m = {}; for (const s of arr) m[s.type] = (m[s.type] || 0) + 1; return m; };
    return el("div", { class: "side" },
      el("h4", {}, el("span", { class: "sw", style: { background: relColor(p), width: ".7em", height: ".7em", borderRadius: "50%", display: "inline-block" } }), pname(p),
        p === v.empire.id ? el("span", { class: "badge info" }, "you") : null, c.owner_before === p ? el("span", { class: "badge" }, "defender") : null),
      ships.length ? el("div", {}, Object.entries(count(ships)).map(([t, n]) => `${n} ${shipClass(t)}`).join(", ")) : null,
      troops.length ? el("div", { class: "dim" }, "Troops: " + Object.entries(count(troops)).map(([t, n]) => `${n} ${troopName(t)}`).join(", ")) : null,
      !ships.length && !troops.length ? el("div", { class: "dim" }, c.owner_before === p ? "system defences only" : "no units listed") : null);
  });
  const rels = Object.entries(c.relations || {}).map(([k, txt]) => el("div", { class: "dim" }, txt));
  const body = el("div", { class: "bbody" }, el("div", { class: "sides" }, sides), rels);
  let phase = null;
  for (const l of c.lines) {
    if (l.phase !== phase) { phase = l.phase; body.append(el("div", { class: "phase" }, PHASE_LABEL[phase] || phase)); }
    body.append(el("div", { class: `bl${/destroy|killed|die|blasted|lost/i.test(l.text) ? " kill" : ""}` }, l.text));
  }
  const ground = groundAfter(c, v, pname);
  if (ground) body.append(ground);
  if (outcome.length) body.append(el("div", { class: "outcome" }, outcome.join(" · ")));
  body.append(el("div", { class: "row-end" }, el("button", { type: "button", class: "small", onclick: () => emit("goto", { x: c.x, y: c.y }) }, "Show on map")));
  return el("details", { class: "battle", open: true, id: `battle-${c.id}` },
    el("summary", {}, el("span", { "aria-hidden": "true" }, "⚔"), el("strong", {}, `Battle at ${place}`), el("span", { class: "dim" }, parts.join(" vs "))), body);
}
// "Ground forces after the battle": each side's troops on the ground, before → after, from the
// log's `ground` (participants only, like the rest of the log; Dave 2026-11-16).  Your side first.
const TROOP_ORDER = ["M", "S", "J", "D", "C", "N", "P", "O"];
function groundAfter(c, v, pname) {
  const ground = c.ground || [];
  if (!ground.length) return null;
  const sides = [...ground].sort((a, b) => (b.owner === v.empire.id) - (a.owner === v.empire.id) || a.owner - b.owner);
  const box = el("div", { class: "ground-after", "data-ground": "after" },
    el("div", { class: "phase" }, "Ground forces after the battle"));
  const grid = el("div", { class: "sides" });
  for (const g of sides) {
    const before = g.before || {}, after = g.after || {};
    const types = [...TROOP_ORDER.filter(t => t in before || t in after), ...Object.keys({ ...before, ...after }).filter(t => !TROOP_ORDER.includes(t)).sort()];
    const nb = Object.values(before).reduce((a, b) => a + b, 0), na = Object.values(after).reduce((a, b) => a + b, 0);
    const rows = types.map(t => {
      const b = before[t] || 0, a = after[t] || 0;
      return el("tr", { class: a < b ? "lost" : "" },
        el("th", { scope: "row" }, troopName(t)), el("td", { class: "num" }, String(b)),
        el("td", { "aria-hidden": "true" }, "→"), el("td", { class: "num" }, el("strong", {}, String(a))),
        el("td", { class: "dim" }, a < b ? `−${b - a}` : a > b ? `+${a - b}` : ""));
    });
    grid.append(el("div", { class: `side${g.owner === v.empire.id ? " mine" : ""}`, "data-owner": String(g.owner) },
      el("h4", {}, el("span", { class: "sw", style: { background: relColor(g.owner), width: ".7em", height: ".7em", borderRadius: "50%", display: "inline-block" } }), pname(g.owner),
        g.owner === v.empire.id ? el("span", { class: "badge info" }, "you") : null),
      el("div", { class: "dim" }, `${nb} → ${na} troop${na === 1 ? "" : "s"}${nb && !na ? " · none left" : ""}`),
      types.length ? el("table", { class: "gtab" },
        el("thead", {}, el("tr", {}, el("th", {}, "Troops"), el("th", { class: "num" }, "Before"), el("th", {}, ""), el("th", { class: "num" }, "After"), el("th", {}, ""))),
        el("tbody", {}, rows)) : null));
  }
  box.append(grid);
  return box;
}
