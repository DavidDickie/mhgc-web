const CLASSIC = new Map();          // "gid|viewAs|seat|turn" -> text (a turn's report never changes)
let classicWide = false;            // the "Wide view" overlay (the report is ~70 columns, the dock less)
function modeBar(box, extra) {
  const sel = el("select", { id: "reportMode", "aria-label": "Report style" },
    el("option", { value: "standard" }, "Standard"), el("option", { value: "classic" }, "Classic text"));
  sel.value = getPref("report.mode", "standard") === "classic" ? "classic" : "standard";
  sel.addEventListener("change", () => { setPref("report.mode", sel.value); renderReport(box); const n = document.getElementById("reportMode"); if (n) n.focus(); });
  return el("div", { class: "report-mode" }, el("label", { for: "reportMode" }, "Report:"), sel, el("span", { class: "spacer" }), extra || null);
}

export function renderReport(box) {
  const v = S.view;
  const old = box.querySelector("#classicReport");
  const keep = old ? { key: old.dataset.key, top: old.scrollTop, left: old.scrollLeft } : null;
  clear(box);
  if (!v) return;
  const r = v.results;
  box.append(el("h2", {}, `Turn ${r.turn} results`, el("span", { class: "dim", style: { fontWeight: 400, fontSize: ".8em" } }, v.game.name)));
  if (getPref("report.mode", "standard") === "classic") { renderClassic(box, v, keep); return; }
  box.append(modeBar(box));
  if (r.turn === 0) box.append(el("p", { class: "hint" }, "The game has just begun. This is your starting position. Give orders and submit; the results of turn 1 appear here."));
  if (v.game.winner) box.append(el("p", { class: "warnc" }, `♛ The ${v.game.winner_name} have won the game.`));
  // AOMT (W-29): the computer wrote this turn's orders
  for (const ev of (r.events || []).filter(x => x.kind === "aomt"))
    box.append(el("p", { class: "notice aomt", id: "aomtNotice", role: "status" }, el("strong", {}, (ev.data && ev.data.source === "draft") ? "Your draft was run. " : "Orders generated automatically. "), ev.text));
  if (S.summary && S.summary.host_handicap && v.seat.host && !v.seat.view_as && !v.game.winner) box.append(hostHandicapNote());
  box.append(digest(v));
  const nb = (r.combats || []).length;
  if (nb) box.append(el("div", { class: "msg", style: { borderLeftColor: "#ff7a45" } },
    el("strong", {}, `⚔ ${nb} battle${nb > 1 ? "s" : ""} this turn`), " ",
    (r.combats || []).map(c => el("button", { type: "button", class: "link", style: { marginLeft: ".6em" }, onclick: () => { const n = box.querySelector(`#battle-${c.id}`); if (n) { n.closest("details.section").open = true; n.scrollIntoView({ behavior: "smooth" }); } emit("goto", { x: c.x, y: c.y }); } }, xy(c.x, c.y)))));

  // jump links
  const jumps = [["orders", "Orders"], ["events", "Events"], ["combat", "Battles"], ["ledger", "Ledger"], ["scans", "Scans"], ["stats", "Stats"]];
  box.append(el("div", { class: "subtabs" }, jumps.map(([id, t]) => el("button", { type: "button", class: "chip-btn ghost", onclick: () => { const n = box.querySelector(`#rep-${id}`); if (n) { n.open = true; n.scrollIntoView({ behavior: "smooth" }); } } }, t))));

  // messages first: they are what players look for
  const msgs = r.messages || [];
  if (msgs.length) box.append(section("messages", "Messages", msgs.length, msgs.map(m => el("div", { class: "msg" },
    el("div", { class: "from" }, `From the ${m.from_name}`, m.broadcast ? el("span", { class: "dim" }, " (to every race)") : null),
    el("pre", {}, m.text)))));

  // order results
  const bad = r.orders.filter(o => !o.ok).length;
  box.append(section("orders", "Order results", r.orders.length ? `${r.orders.length - bad} ok${bad ? `, ${bad} failed` : ""}` : 0,
    r.orders.length ? r.orders.map(o => el("div", { class: `res-line ${o.ok ? "good" : "bad"}` },
      el("span", { class: "ic", "aria-label": o.ok ? "done" : "failed" }, o.ok ? "✓" : "✗"),
      el("div", {}, el("code", {}, o.text), o.error ? el("div", { class: "err" }, o.error) : null,
        o.messages.length ? el("div", { class: "dim" }, o.messages.join(" · ")) : null)))
      : el("p", { class: "hint" }, "No orders were given this turn.")));

  // events by section
  const bySec = {};
  for (const e of r.events) (bySec[e.section || "general"] ||= []).push(e);
  const evBody = el("div");
  for (const sec of SECTION_ORDER) {
    const list = bySec[sec];
    if (!list) continue;
    evBody.append(el("h4", {}, SECTION_LABEL[sec] || sec));
    for (const e of list) {
      evBody.append(el("div", { class: `res-line ${BAD.has(e.kind) ? "bad" : GOOD.has(e.kind) ? "good" : ""}` },
        el("span", { class: "ic", "aria-hidden": "true" }, KIND_ICON[e.kind] || "•"),
        el("div", {}, e.text), e.system !== null && e.system !== undefined ? sysLink(e.system) : null));
    }
  }
  box.append(section("events", "Events", r.events.length, r.events.length ? evBody : el("p", { class: "hint" }, "A quiet turn.")));

  // battles
  const cbs = r.combats || [];
  box.append(section("combat", "Battles", cbs.length, cbs.length ? cbs.map(c => battle(c, v)) : el("p", { class: "hint" }, "No battles involved you this turn."), cbs.length > 0));

  // ledger
  box.append(section("ledger", "Maintenance ledger", null, ledger(r), false));

  // scans
  box.append(section("scans", "Scans", `${v.scans.ships.length} ships, ${v.scans.systems.length} systems`, scans(v), false));

  // stats
  const st = r.stats || {};
  box.append(section("stats", "Statistics and ranks", null, el("div", {},
    st.unranked ? el("p", { class: "warnc", id: "unrankedNote" }, `Victory points: ${st.vp ?? "–"} (host, unranked). As host of a multi-player game your race can't win and earns no ranking VP; it is not ranked, and the others rank as if it weren't there.`)
      : el("p", {}, `Victory points: ${st.vp ?? "–"} of ${st.vp_needed ?? v.game.vp_to_win}. Ranks are among all races, computer empires included (1 = first or tied).`),
    el("div", { class: "tbl-wrap" }, el("table", { class: "tbl" },
      el("thead", {}, el("tr", {}, el("th", { scope: "col" }, "Stat"), el("th", { scope: "col", class: "num" }, "Value"), el("th", { scope: "col", class: "num" }, "Rank"))),
      el("tbody", {}, Object.entries(st.values || {}).map(([k, val]) => el("tr", {}, el("td", { title: STAT_LABEL[k] || k }, `${k} `, el("span", { class: "dim" }, STAT_LABEL[k] || "")), el("td", { class: "num" }, fmt(val, 2)), el("td", { class: "num" }, st.ranks && st.ranks[k] !== undefined ? st.ranks[k] : "–")))))),
    el("p", {}, el("button", { type: "button", class: "link", onclick: () => emit("showTab", "stats") }, "Graphs over all turns →"))), false));
}

function renderClassic(box, v, keep) {
  const turn = v.game.turn;
  const key = `${S.gid}|${S.viewAs ?? ""}|${v.seat ? v.seat.seat : ""}|${turn}`;
  const name = `${v.empire.name}_turnresults_${turn}.txt`;
  const pre = el("pre", { class: "classic-report", id: "classicReport", tabindex: 0, dataset: { key },
    "aria-label": `Turn ${turn} report for the ${v.empire.name}, classic text` }, "Loading the classic report…");
  const copy = el("button", { type: "button", class: "small", id: "classicCopy", disabled: true, onclick: async () => {
    const t = CLASSIC.get(key);
    if (t && await copyText(t)) toast("Report copied to the clipboard.", "good", 2500); else toast("Couldn't copy the report.", "error");
  } }, "Copy");
  const dl = el("button", { type: "button", class: "small", id: "classicDownload", disabled: true, title: name, onclick: () => {
    const t = CLASSIC.get(key);
    if (!t) return;
    const url = URL.createObjectURL(new Blob([t], { type: "text/plain;charset=utf-8" }));
    const a = el("a", { href: url, download: name });
    document.body.append(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 2000);
  } }, "Download (.txt)");
  const wrap = el("div", { class: `classic-wrap${classicWide ? " wide" : ""}`, id: "classicWrap" });
  const wide = el("button", { type: "button", class: "small", id: "classicWide", "aria-pressed": classicWide ? "true" : "false",
    title: "Show the report over the map, at full width (Esc to close)", onclick: () => setWide(!classicWide) }, classicWide ? "Close wide view" : "Wide view");
  const setWide = on => {
    classicWide = on;
    wrap.classList.toggle("wide", on);
    wide.setAttribute("aria-pressed", on ? "true" : "false");
    wide.textContent = on ? "Close wide view" : "Wide view";
    pre.focus();
  };
  wrap.addEventListener("keydown", e => { if (e.key === "Escape" && classicWide) { e.stopPropagation(); setWide(false); } });
  clear(wrap, modeBar(box, [copy, dl, wide]), pre);
  box.append(wrap);
  const fill = t => {
    pre.textContent = t;
    copy.disabled = dl.disabled = false;
    if (keep && keep.key === key) { pre.scrollTop = keep.top; pre.scrollLeft = keep.left; }
  };
  if (CLASSIC.has(key)) { fill(CLASSIC.get(key)); return; }
  api(`/api/games/${S.gid}/report.txt?turn=${turn}`, { gid: S.gid, text: true }).then(t => {
    CLASSIC.set(key, t);
    while (CLASSIC.size > 12) CLASSIC.delete(CLASSIC.keys().next().value);
    if (pre.isConnected && pre.dataset.key === key) fill(t);
  }).catch(e => { if (pre.isConnected) pre.textContent = `Couldn't load the classic report: ${e.message}`; });
}
async function copyText(t) {
  try { await navigator.clipboard.writeText(t); return true; } catch { /* no permission: fall back */ }
  const ta = el("textarea", { style: { position: "fixed", left: "-9999px", top: "0" }, "aria-hidden": "true" });
  ta.value = t;
  document.body.append(ta);
  ta.select();
  let ok = false;
  try { ok = document.execCommand("copy"); } catch { ok = false; }
  ta.remove();
  return ok;
}

function digest(v) {
  const r = v.results, e = v.empire;
  const prev = S.stats && S.stats.turns.find(t => t.turn === r.turn - 1);
  const cur = r.stats && r.stats.values ? r.stats.values : e.stats;
  const tile = (k, val, d, title) => el("div", { class: "tile", title },
    el("div", { class: "k" }, k), el("div", { class: "v" }, val),
    d !== null && d !== undefined && d !== 0 ? el("div", { class: `d ${d > 0 ? "up" : "down"}` }, `${d > 0 ? "▲" : "▼"} ${fmt(Math.abs(d), 1)}`) : el("div", { class: "d dim" }, " "));
  const dv = (k, now) => prev && prev.values && prev.values[k] !== undefined ? now - prev.values[k] : null;
  const de = k => prev && prev.economy && prev.economy[k] !== undefined ? r.economy[k] - prev.economy[k] : null;
  const p = r.economy.production || {};
  return el("div", { class: "digest" },
    tile("EU stockpile", fmt(r.economy.eu), de("eu"), "Energy units in the stockpile"),
    tile("IU depot", fmt(r.economy.iu_depot), de("iu_depot"), "Industrial units in the supply depot"),
    tile("VP", `${r.stats.vp ?? e.vp}/${r.stats.vp_needed ?? v.game.vp_to_win}`, prev ? (r.stats.vp - prev.vp) : null, "Victory points"),
    tile("Systems", fmt(cur.SYS), dv("SYS", cur.SYS)),
    tile("Population", fmt(cur.POP, 1), dv("POP", cur.POP)),
    tile("NNP", fmt(cur.NNP), dv("NNP", cur.NNP), STAT_LABEL.NNP),
    tile("Production", `${fmt(p.AU)}/${fmt(p.IU)}/${fmt(p.EU)}`, null, "AU / IU / EU produced this turn"),
    tile("Warships", fmt(cur.WAR), dv("WAR", cur.WAR)));
}

function ledger(r) {
  const rows = r.maintenance || [];
  if (!rows.length) return el("p", { class: "hint" }, "No ledger this turn.");
  const cell = n => el("td", { class: `num ${n < 0 ? "neg" : n > 0 ? "pos" : ""}` }, n ? fmt(n) : "");
  const total = l => l.kind === "initial" || l.kind === "final";
  // IU = the supply depot, EU = the stockpile; initial + every line = final.  IUs that orders
  // take from (or salvage returns to) system stockpiles get their own column.
  const sys = rows.some(l => l.system_iu);
  return el("div", {}, el("div", { class: "tbl-wrap" }, el("table", { class: "tbl ledger" },
    el("thead", {}, el("tr", {}, el("th", { scope: "col" }, "Item"), el("th", { scope: "col", class: "num", title: "IU supply depot" }, "Depot IU"), el("th", { scope: "col", class: "num" }, "EU"),
      sys ? el("th", { scope: "col", class: "num", title: "IUs from or to your systems' stockpiles (not the depot)" }, "System IU") : null)),
    el("tbody", {}, rows.map(l => el("tr", { class: total(l) ? "total" : "" },
      el("td", {}, ledgerText(l)), total(l) ? el("td", { class: "num" }, fmt(l.iu)) : cell(l.iu),
      total(l) ? el("td", { class: "num" }, fmt(l.eu)) : cell(l.eu),
      sys ? (total(l) ? el("td") : cell(l.system_iu || 0)) : null))))),
    sys ? el("p", { class: "hint" }, "System IU is spent from (or returned to) your systems' own stockpiles, not the supply depot, so it is not part of the depot total.") : null);
}
function ledgerText(l) {
  const t = String(l.text || l.kind);
  // turns run before 2026-11-12 stored the old all-caps ledger texts
  if (t !== t.toUpperCase()) return t;
  if (l.kind === "ship" && l.ship !== undefined) {
    const s = S.view.ships.find(q => q.number === l.ship);
    return s ? `Ship ${l.ship} (${s.class})` : `Ship ${l.ship}`;
  }
  return t.charAt(0) + t.slice(1).toLowerCase();
}

