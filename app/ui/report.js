function sysLink(id, label) {
  const s = knownSystems().find(q => q.id === id);
  if (!s) return null;
  return el("button", { type: "button", class: "link sys-link", onclick: () => emit("goto", { x: s.x, y: s.y }) }, label || s.name || xy(s.x, s.y));
}
function section(id, title, count, body, open = true) {
  return el("details", { class: "section", open: open || undefined, id: `rep-${id}` },
    el("summary", {}, el("h3", {}, title, count !== undefined && count !== null ? el("span", { class: "badge" }, String(count)) : null)), body);
}

// "Report: Standard | Classic text" (Dave 2026-11-15), kept in the browser's prefs.  The classic
